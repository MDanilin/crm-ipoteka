    $tblMatrix.Cell(1, $c + 2).Range.Font.Bold = $true
    $tblMatrix.Cell(1, $c + 2).Range.Font.Size = 9
    $tblMatrix.Cell(1, $c + 2).Shading.BackgroundPatternColor = 0xF3F4F6
}

