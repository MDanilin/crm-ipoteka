# ── Стили ─────────────────────────────────────────────────────────────────────
function SetFont($sel, $size, $bold = $false, $color = 0x000000) {
    $sel.Font.Size  = $size
    $sel.Font.Bold  = $bold
    $sel.Font.Color = $color
    $sel.Font.Name  = "Calibri"
}

function Heading1($sel, $text) {
    $sel.Style = "Заголовок 1"
    $sel.TypeText($text)
    $sel.TypeParagraph()
}

function Heading2($sel, $text) {
    $sel.Style = "Заголовок 2"
    $sel.TypeText($text)
    $sel.TypeParagraph()
}

function Body($sel, $text) {
    $sel.Style = "Обычный"
    SetFont $sel 11
    $sel.TypeText($text)
    $sel.TypeParagraph()
}

function BulletItem($sel, $text) {
    $sel.Style = "Список с маркерами"
    $sel.TypeText($text)
    $sel.TypeParagraph()
}

